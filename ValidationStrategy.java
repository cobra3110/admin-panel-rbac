package com.example.adminpanel.service.validation;

/**
 * ПАТТЕРН "СТРАТЕГИЯ" (Strategy).
 * Инкапсулирует взаимозаменяемые алгоритмы валидации для разных сущностей.
 * Также демонстрирует принципы SOLID:
 *  - S: каждая реализация отвечает только за валидацию одного типа
 *  - L: все реализации взаимозаменяемы
 *  - D: сервисы зависят от этой абстракции, а не от конкретных реализаций
 */
public interface ValidationStrategy<T> {
    void validate(T entity);
}